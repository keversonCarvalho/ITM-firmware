"""Generate fixed OD descriptors from the ITM EDS. No host CANopen installation."""
import argparse
import configparser
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]


def generate():
    eds = configparser.ConfigParser(interpolation=None)
    eds.read(ROOT / 'config/canopen/itm-100.eds', encoding='utf-8')
    rows = ['/* Generated by tools/generate_n7space_od.py; do not edit. */']
    for section in eds.sections():
        match = re.fullmatch(r'([0-9A-Fa-f]{4})(?:sub([0-9A-Fa-f]+))?', section)
        if not match or 'DataType' not in eds[section]:
            continue
        entry = eds[section]
        index = int(match[1], 16)
        sub = int(match[2], 16) if match[2] else 0
        dtype = int(entry['DataType'], 0)
        if dtype not in (5, 6, 7, 9, 10):
            raise ValueError(f'Unsupported static OD type: {section}')
        access = {'ro': 'CO_ACCESS_RO', 'rw': 'CO_ACCESS_RW',
                  'wo': 'CO_ACCESS_WO', 'const': 'CO_ACCESS_CONST'}[entry['AccessType']]
        default = entry.get('DefaultValue', '0')
        value = 0 if dtype in (9, 10) else int(default, 0)
        code = int(eds[f'{index:04X}']['ObjectType'], 0)
        rows.append(f'{{0x{index:04X}, {sub}, {dtype}, {code}, {access}, {value}UL}},')
    return '\n'.join(rows) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'generated/canopen/n7space_od.inc'
    expected = generate()
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit('N7 Space OD is stale; run tools/generate_n7space_od.py')
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected, encoding='utf-8')
